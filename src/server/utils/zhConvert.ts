/** 简体 → 繁体（由 T2S 反推，一字多繁时取首个） */
const S2T_MAP: Record<string, string> = (() => {
    const m: Record<string, string> = {}
    for (const [t, s] of Object.entries(T2S_MAP)) {
        if (!m[s]) m[s] = t
    }
    return m
})()

export const hasTraditionalChars = (text: string): boolean =>
    Array.from(String(text || '')).some(ch => Object.prototype.hasOwnProperty.call(T2S_MAP, ch))

export const hasSimplifiedChars = (text: string): boolean =>
    Array.from(String(text || '')).some(ch => Object.prototype.hasOwnProperty.call(S2T_MAP, ch))

/** 繁体 → 简体 */
export const toSimplified = (text: string): string =>
    Array.from(String(text || '')).map(ch => T2S_MAP[ch] ?? ch).join('')

/** 简体 → 繁体 */
export const toTraditional = (text: string): string =>
    Array.from(String(text || '')).map(ch => S2T_MAP[ch] ?? ch).join('')

/**
 * 生成搜索用的词变体：原词在前，其后是按当前字形生成的另一种写法。
 * 例：'黄霄雲' → ['黄霄雲', '黄霄云']；'黄霄云' → ['黄霄云', '黄霄雲']
 * 两个字表都命不中时只返回原词（调用方行为与未转换时一致）。
 */
export function buildQueryVariants(query: string): string[] {
    const q = String(query || '').trim()
    if (!q) return []
    const out: string[] = [q]
    if (hasTraditionalChars(q)) {
        const s = toSimplified(q)
        if (s && s !== q) out.push(s)
    } else if (hasSimplifiedChars(q)) {
        const t = toTraditional(q)
        if (t && t !== q) out.push(t)
    }
    return out
}
